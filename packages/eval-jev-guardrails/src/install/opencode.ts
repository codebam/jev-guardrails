/**
 * Idempotent OpenCode installer.
 *
 * Project scope writes `.opencode/package.json` (dependency declaration for
 * local plugin imports) and `.opencode/plugins/eval-jev-guardrails.js`.
 * Global scope writes the same pair under `~/.config/opencode/`.
 *
 * @module @codebam/eval-jev-guardrails/install/opencode
 */
import { homedir } from 'node:os'
import { join } from 'node:path'
import { PACKAGE_VERSION } from '../version.js'
import type { InstallResult } from './types.js'
import { updateJsonFile, writeTextIfChanged } from './util.js'

/** Options for {@link installOpenCode}. */
export interface InstallOpenCodeOptions {
  /** `global` targets `$XDG_CONFIG_HOME/opencode`; default is project scope. */
  global?: boolean
  /** Project root for `--project`; defaults to `process.cwd()`. */
  cwd?: string
  /** Home directory for global scope; defaults to `os.homedir()`. */
  home?: string
  env?: NodeJS.ProcessEnv
}

/** Directory OpenCode reads local plugins from for the chosen scope. */
export function openCodeConfigDir(options: InstallOpenCodeOptions = {}): string {
  const env = options.env ?? process.env
  if (options.global === true) {
    const xdg = env.XDG_CONFIG_HOME?.trim()
    const base = xdg !== undefined && xdg.length > 0 ? xdg : join(options.home ?? homedir(), '.config')
    return join(base, 'opencode')
  }
  return join(options.cwd ?? process.cwd(), '.opencode')
}

/** Render the generated OpenCode plugin module. */
export function renderOpenCodePluginSource(version: string = PACKAGE_VERSION): string {
  return `/**
 * Generated by \`eval-jev install opencode\` (@codebam/eval-jev-guardrails v${version}).
 *
 * This file is safe to delete; re-run the installer to regenerate it.
 * OpenCode auto-loads modules from .opencode/plugins/ (project) or
 * ~/.config/opencode/plugins/ (global).
 *
 * Configuration is read at hook time:
 *   EVAL_API_KEY / EVAL_BASE_URL  (else ~/.config/eval-jev/config.json)
 *   EVAL_REVIEW_MODE=deny|allow   (default deny: a review verdict blocks)
 *   EVAL_FAIL_MODE=open|review|closed (default open)
 *   EVAL_SKIP_TOOLS=Read,List     (exact tool names to pass through)
 */
import { createOpenCodePlugin } from '@codebam/eval-jev-guardrails/opencode'

export const EvalJevGuardrailsPlugin = createOpenCodePlugin()
`
}

/** Install the real `tool.execute.before` OpenCode hook. */
export function installOpenCode(options: InstallOpenCodeOptions = {}): InstallResult {
  const base = openCodeConfigDir(options)
  const packagePath = join(base, 'package.json')
  const pluginPath = join(base, 'plugins', 'eval-jev-guardrails.js')
  const scope = options.global === true ? 'global' : 'project'

  const packageChange = updateJsonFile(packagePath, (current) => {
    const dependencies =
      current.dependencies !== null && typeof current.dependencies === 'object' && !Array.isArray(current.dependencies)
        ? { ...(current.dependencies as Record<string, unknown>) }
        : {}
    dependencies['@codebam/eval-jev-guardrails'] = `^${PACKAGE_VERSION}`
    return {
      ...current,
      type: typeof current.type === 'string' && current.type.length > 0 ? current.type : 'module',
      dependencies,
    }
  })
  const pluginChange = writeTextIfChanged(pluginPath, renderOpenCodePluginSource())

  const files = [packageChange, pluginChange]
  return {
    harness: 'opencode',
    scope,
    target: base,
    changed: files.some((file) => file.status !== 'unchanged'),
    files,
    warnings: [],
    notes: [
      `OpenCode auto-loads ${pluginPath}.`,
      'The hook calls POST /v1/evaluate on every tool call; block/support throws before execution.',
      'Set EVAL_REVIEW_MODE=allow to let review verdicts run, and EVAL_FAIL_MODE=open|review|closed for service failures.',
    ],
  }
}
